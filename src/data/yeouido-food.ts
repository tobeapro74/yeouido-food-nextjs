// 유틸리티 함수
export function getAllRestaurants(): Restaurant[] {
  const all: Restaurant[] = [];
  const cats = ["한식", "양식", "중식", "일식", "동남아식"] as const;
  for (const cat of cats) {
    all.push(...yeouidoFoodMap[cat]);
  }
  return all;
}

export function getRestaurantsByCategory(category: string): Restaurant[] {
  if (category === "전체") {
    return getAllRestaurants();
  }
  return yeouidoFoodMap[category as keyof typeof yeouidoFoodMap] || [];
}

export function getRestaurantsByRegion(region: string): Restaurant[] {
  const all = getAllRestaurants();
  if (region === "전체") {
    return all;
  }
  return all.filter((r) => r.지역 === region);
}

export function getRestaurantsByCategoryAndRegion(category: string, region: string): Restaurant[] {
  let results = category === "전체" ? getAllRestaurants() : (yeouidoFoodMap[category as keyof typeof yeouidoFoodMap] || []);

  if (region !== "전체") {
    results = results.filter((r) => r.지역 === region);
  }

  return results;
}

// 인기 맛집 (카테고리별 최고 평점 맛집 1개씩)
export interface PopularRestaurant extends Restaurant {
  카테고리명: string;
}

export function getPopularRestaurants(): PopularRestaurant[] {
  const cats = ["한식", "양식", "중식", "일식", "동남아식"] as const;
  const topByCategory: PopularRestaurant[] = [];

  for (const cat of cats) {
    const items = yeouidoFoodMap[cat];
    if (items && items.length > 0) {
      const sorted = [...items]
        .filter((r) => r.평점)
        .sort((a, b) => (b.평점 || 0) - (a.평점 || 0));
      if (sorted.length > 0) {
        topByCategory.push({ ...sorted[0], 카테고리명: cat });
      }
    }
  }

  return topByCategory;
}

// 이미지 URL 생성 (Lorem Picsum 사용)
export function getPlaceholderImage(name: string): string {
  const seed = name.split("").reduce((a, c) => a + c.charCodeAt(0), 0);
  return `https://picsum.photos/seed/${seed}/400/300`;
}

// 구글 맵 링크 생성
export function getGoogleMapsLink(name: string, address: string): string {
  const query = `${name} ${address}`.trim();
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`;
}

